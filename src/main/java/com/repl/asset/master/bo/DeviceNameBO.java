package com.repl.asset.master.bo;

import java.time.LocalDate;
import java.time.LocalTime;

import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;

/**
 * One named machine, in and out.
 *
 * The user fills in device_id, model_id, device_name, description and status. device_name_label
 * and model_name are resolved on the way out for the table, create_date and create_time are the
 * server's, and all of those are ignored on the way in.
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
public class DeviceNameBO {

	@JsonProperty("id")
	private Long id;

	/** The chosen device, as an id from the device master. This is what the form sends. */
	@JsonProperty("device_id")
	private Long device_id;

	/** Resolved from device_id on the way out, for the table. Ignored on the way in. */
	@JsonProperty("device")
	private String device;

	/** The chosen model, as an id from the model master. This is what the form sends. */
	@JsonProperty("model_id")
	private Long model_id;

	/** Resolved from model_id on the way out, for the table. Ignored on the way in. */
	@JsonProperty("model_name")
	private String model_name;

	/** What the machine is called — the one field typed here. */
	@JsonProperty("device_name")
	private String device_name;

	@JsonProperty("description")
	private String description;

	/** Generated by the server when the name is created, e.g. DE26HR01007. Ignored on the way in. */
	@JsonProperty("reference_no")
	private String reference_no;

	public String getReference_no() {
		return reference_no;
	}

	public void setReference_no(String reference_no) {
		this.reference_no = reference_no;
	}

	@JsonProperty("create_date")
	@JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd")
	private LocalDate create_date;

	@JsonProperty("create_time")
	@JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "HH:mm")
	private LocalTime create_time;

	/** 1 = active, 0 = inactive. -1 is set by delete and never arrives from a form. */
	@JsonProperty("status")
	private Integer status;

	public Long getId() {
		return id;
	}

	public void setId(Long id) {
		this.id = id;
	}

	public Long getDevice_id() {
		return device_id;
	}

	public void setDevice_id(Long device_id) {
		this.device_id = device_id;
	}

	public String getDevice() {
		return device;
	}

	public void setDevice(String device) {
		this.device = device;
	}

	public Long getModel_id() {
		return model_id;
	}

	public void setModel_id(Long model_id) {
		this.model_id = model_id;
	}

	public String getModel_name() {
		return model_name;
	}

	public void setModel_name(String model_name) {
		this.model_name = model_name;
	}

	public String getDevice_name() {
		return device_name;
	}

	public void setDevice_name(String device_name) {
		this.device_name = device_name;
	}

	public String getDescription() {
		return description;
	}

	public void setDescription(String description) {
		this.description = description;
	}

	public LocalDate getCreate_date() {
		return create_date;
	}

	public void setCreate_date(LocalDate create_date) {
		this.create_date = create_date;
	}

	public LocalTime getCreate_time() {
		return create_time;
	}

	public void setCreate_time(LocalTime create_time) {
		this.create_time = create_time;
	}

	public Integer getStatus() {
		return status;
	}

	public void setStatus(Integer status) {
		this.status = status;
	}
}
